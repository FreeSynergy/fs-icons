#!/usr/bin/env python3
"""Write EXCLUDED.md for a third-party set: every SVG that check_svg.py flags, with the reason.
Usage: gen_excluded.py <set dir> [--max-bytes N]
Files are never changed; they are only left out of the package (changing third-party logos is not ours to do).
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_svg  # noqa: E402


def excluded(d: Path, max_bytes: int = check_svg.MAX_BYTES) -> dict[str, list[str]]:
    out = {}
    for f in check_svg.collect([str(d)]):
        probs = sorted(set(check_svg.check_bytes(f.read_bytes(), max_bytes)))
        if probs:
            out[str(f.relative_to(d))] = probs
    return out


def render(name: str, items: dict[str, list[str]]) -> str:
    lines = [f"# Excluded from the package: {name}", "",
             "Generated by `scripts/gen_excluded.py` (rules of `scripts/check_svg.py`). These files stay in the tree",
             "unchanged and are not shipped; they are third-party works and are not edited by us. Count: "
             f"{len(items)}.", "", "| File | Reason |", "|---|---|"]
    for f, probs in items.items():
        lines.append(f"| `{f}` | {'; '.join(p.replace('|', '/')[:90] for p in probs)} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    d = Path(sys.argv[1])
    items = excluded(d)
    (d / "EXCLUDED.md").write_text(render(d.name, items))
    print(f"{d}: {len(items)} files excluded")
